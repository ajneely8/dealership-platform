/**
 * LOCAL DEVELOPMENT without Docker.
 * Boots a real PostgreSQL (embedded-postgres) and a real Redis (redis-memory-server), applies
 * migrations, seeds the first admin, then runs the web app and the workers.
 * Set FIXTURE_SITE=1 to also run the local test "dealership" used by the automated tests.
 *
 *   npm run dev   →  http://localhost:5310   (dev mode: pages compile on first visit, so the first open of each is slow)
 *   npm run fast  →  same, but builds once and serves the optimised app; every page is quick
 *
 * Database files live in %LOCALAPPDATA%/dealer-intel (outside OneDrive). Redis is in-memory, so queued
 * jobs are lost on restart; the scheduler re-creates anything that matters.
 * The generated dev admin login is written to .data/dev-credentials.txt (git-ignored).
 */
import { spawn, spawnSync } from "node:child_process";
import { randomBytes } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import EmbeddedPostgres from "embedded-postgres";
import { RedisMemoryServer } from "redis-memory-server";

const root = fileURLToPath(new URL("..", import.meta.url));
process.chdir(root);
if (existsSync(".env")) process.loadEnvFile(".env");

const dataDir = path.join(process.env.LOCALAPPDATA ?? path.join(os.homedir(), ".local", "share"), "dealer-intel");
const pgDir = path.join(dataDir, "pg");
mkdirSync(dataDir, { recursive: true });
mkdirSync(".data", { recursive: true });

const PG_PORT = Number(process.env.DEV_PG_PORT ?? 54330);
const REDIS_PORT = Number(process.env.DEV_REDIS_PORT ?? 63790);
const WEB_PORT = process.env.PORT ?? "5310";
const FIXTURE_PORT = process.env.FIXTURE_PORT ?? "5311";

// Persisted so sessions and the admin login survive restarts.
const credFile = path.join(".data", "dev-credentials.txt");
let creds;
if (existsSync(credFile)) {
  creds = Object.fromEntries(readFileSync(credFile, "utf8").split(/\r?\n/).filter((l) => l.includes("=")).map((l) => [l.slice(0, l.indexOf("=")), l.slice(l.indexOf("=") + 1)]));
} else {
  creds = { ADMIN_EMAIL: "admin@dealer-intel.local", ADMIN_PASSWORD: randomBytes(12).toString("base64url"), SESSION_SECRET: randomBytes(48).toString("hex") };
  writeFileSync(credFile, `# Local development only. Generated by scripts/dev-local.mjs.\n${Object.entries(creds).map(([k, v]) => `${k}=${v}`).join("\n")}\n`);
}

console.log("[dev] starting PostgreSQL…");
const pg = new EmbeddedPostgres({ databaseDir: pgDir, user: "postgres", password: "postgres", port: PG_PORT, persistent: true, onLog: () => {}, onError: (e) => console.error("[pg]", e) });
if (!existsSync(path.join(pgDir, "PG_VERSION"))) await pg.initialise();
await pg.start();
await pg.createDatabase("dealer_intel").catch(() => undefined); // already exists on later runs

console.log("[dev] starting Redis…");
const redis = new RedisMemoryServer({ instance: { port: REDIS_PORT } });
await redis.getPort();

const env = {
  ...process.env,
  NODE_ENV: "development",
  APP_URL: `http://localhost:${WEB_PORT}`,
  DATABASE_URL: `postgres://postgres:postgres@127.0.0.1:${PG_PORT}/dealer_intel`,
  REDIS_URL: `redis://127.0.0.1:${REDIS_PORT}`,
  STORAGE_DRIVER: process.env.STORAGE_DRIVER ?? "local",
  STORAGE_LOCAL_DIR: process.env.STORAGE_LOCAL_DIR ?? path.join(dataDir, "evidence"),
  ALLOW_LOCAL_TARGETS: "true",
  FIXTURE_PORT,
  ...creds,
};

for (const script of ["src/db/migrate.ts", "src/db/seed.ts"]) {
  const r = spawnSync("npx", ["tsx", script], { stdio: "inherit", shell: true, env });
  if (r.status !== 0) {
    await pg.stop();
    await redis.stop();
    process.exit(r.status ?? 1);
  }
}

const prod = process.env.MODE === "prod" || process.argv.includes("--prod");
if (prod) {
  console.log("[dev] building the optimised app once (about a minute)…");
  // OneDrive can hold a lock on files in .next while it syncs; a stale build dir then makes
  // "next build" fail with EPERM. Clear it first (with retries) and try the build twice.
  const clearBuildDir = () => {
    try {
      rmSync(".next", { recursive: true, force: true, maxRetries: 10, retryDelay: 500 });
    } catch (err) {
      console.warn("[dev] could not fully clear .next:", err.message);
    }
  };
  clearBuildDir();
  let b = spawnSync("npx", ["next", "build"], { stdio: "inherit", shell: true, env: { ...env, NODE_ENV: "production" } });
  if (b.status !== 0) {
    console.log("[dev] build failed once; clearing .next and retrying…");
    clearBuildDir();
    b = spawnSync("npx", ["next", "build"], { stdio: "inherit", shell: true, env: { ...env, NODE_ENV: "production" } });
  }
  if (b.status !== 0) {
    await pg.stop();
    await redis.stop();
    process.exit(b.status ?? 1);
  }
}
const children = [
  prod
    ? spawn("npx", ["next", "start", "-p", WEB_PORT], { stdio: "inherit", shell: true, env: { ...env, NODE_ENV: "production", STORAGE_DRIVER: "local" } })
    : spawn("npx", ["next", "dev", "-p", WEB_PORT], { stdio: "inherit", shell: true, env }),
  spawn("npx", ["tsx", "src/workers/index.ts"], { stdio: "inherit", shell: true, env }),
];
if (process.env.FIXTURE_SITE === "1") children.push(spawn("npx", ["tsx", "tests/fixtures/site-server.ts"], { stdio: "inherit", shell: true, env }));
console.log(`[dev] app      → http://localhost:${WEB_PORT}`);
console.log(`[dev] login    → see ${path.join("dealer-intel", credFile)}`);
if (process.env.FIXTURE_SITE === "1") console.log(`[dev] fixture  → http://127.0.0.1:${FIXTURE_PORT}  (local test "dealership" for automated tests only)`);

let closing = false;
const shutdown = async () => {
  if (closing) return;
  closing = true;
  for (const c of children) c.kill();
  await redis.stop().catch(() => undefined);
  await pg.stop().catch(() => undefined);
  process.exit(0);
};
process.on("SIGINT", shutdown);
process.on("SIGTERM", shutdown);
for (const c of children) c.on("exit", (code) => code && !closing && console.error(`[dev] a child process exited with code ${code}`));
